// Turns the Blender mask grids into figure-masks.js: a run-length encoded
// group index per pixel, plus one keyboard hotspot per group and view.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const outDir = process.argv[2] || join(here, "out");

const sandbox = {};
vm.runInNewContext(readFileSync(join(root, "data.js"), "utf8") + "\nthis.SESSION = SESSION;", sandbox);
const groups = sandbox.SESSION.groups;

function insideDistance(cells, w, h, code) {
  // two-pass chamfer distance (in pixels) to the nearest pixel outside the group
  const far = w + h;
  const d = new Int32Array(w * h);
  for (let i = 0; i < d.length; i++) d[i] = cells[i] === code ? far : 0;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      if (!d[i]) continue;
      const up = y ? d[i - w] : 0;
      const left = x ? d[i - 1] : 0;
      d[i] = Math.min(d[i], up + 1, left + 1);
    }
  }
  for (let y = h - 1; y >= 0; y--) {
    for (let x = w - 1; x >= 0; x--) {
      const i = y * w + x;
      if (!d[i]) continue;
      const down = y < h - 1 ? d[i + w] : 0;
      const right = x < w - 1 ? d[i + 1] : 0;
      d[i] = Math.min(d[i], down + 1, right + 1);
    }
  }
  return d;
}

const result = {};
for (const view of ["front", "back"]) {
  const grid = JSON.parse(readFileSync(join(outDir, `mask-${view}.grid.json`), "utf8"));
  const { w, h, ids, runs } = grid;
  const cells = new Uint8Array(w * h);
  let at = 0;
  for (const [value, length] of runs) {
    cells.fill(value, at, at + length);
    at += length;
  }
  if (at !== w * h) throw new Error(`${view}: runs cover ${at} of ${w * h} pixels`);

  const hotspots = {};
  for (const group of groups) {
    if (!group.views.includes(view)) continue;
    const code = ids.indexOf(group.id) + 2;
    let sx = 0, sy = 0, n = 0;
    // one side only, so a paired muscle's hotspot does not land on the midline
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w / 2; x++) {
        if (cells[y * w + x] === code) { sx += x; sy += y; n++; }
      }
    }
    if (!n) throw new Error(`${view}: no pixels for ${group.id}`);
    // deepest pixel (farthest from the group's edge), ties broken toward the centroid,
    // so thin slivers still get a hotspot that hit-tests to the group
    const depth = insideDistance(cells, w, h, code);
    let cx = 0, cy = 0, bestDepth = -1, bestPull = Infinity;
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w / 2; x++) {
        const d = depth[y * w + x];
        if (!d) continue;
        const pull = (x - sx / n) ** 2 + (y - sy / n) ** 2;
        if (d > bestDepth || (d === bestDepth && pull < bestPull)) {
          bestDepth = d; bestPull = pull; cx = x; cy = y;
        }
      }
    }
    hotspots[group.id] = [+(cx / w * 100).toFixed(2), +(cy / h * 100).toFixed(2)];
  }

  const encoded = runs.map(([value, length]) => value.toString(36) + length.toString(36)).join(".");
  result[view] = { w, h, ids, runs: encoded, hotspots };
}

writeFileSync(
  join(root, "figure-masks.js"),
  "// Generated by tools/build-masks.mjs from the Z-Anatomy renders. Do not edit.\n" +
  `const FIGURE_MASKS = ${JSON.stringify(result)};\n`,
);
console.log("wrote figure-masks.js", Object.fromEntries(Object.entries(result).map(([v, r]) => [v, Object.keys(r.hotspots).length])));
